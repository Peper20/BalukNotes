#!/usr/bin/env python3
"""Линт исходников конспекта: то, что typst пропускает молча.

  1. Сырая десятичная запятая в матрежиме: `$0,5$` печатается «0, 5».
     Нужно `$dc("0,5")$` (см. lib/math.typ).
  2. Конструкция `{,}` из LaTeX — в typst скобки выводятся буквально.
  3. smallcaps(...) — у шрифтов может не быть кириллических капителей, typst
     молча печатает строчные. Нужно капитель(...) из библиотеки.

Запуск из корня проекта:  python3 lib/lint.py [папка ...]
По умолчанию проверяет все .typ в проекте, кроме самой библиотеки.
Код возврата 1, если есть находки.
Перенесено из решебника по теорверу (там линт поймал десятки таких мест).
"""
import pathlib
import re
import sys

МАТРЕЖИМ = re.compile(r"\$[^$]*\$", re.S)
ДЕСЯТИЧНАЯ = re.compile(r"(?<![\w.])(\d+),(\d+)")

# Где запятая — законный разделитель: вырезаем до поиска дробей.
РАЗДЕЛИТЕЛИ = [
    re.compile(r'dc\("[^"]*"\)'),                          # уже обёрнутое
    re.compile(r"[NUE]\s*\(\s*[\d.]+\s*,\s*[\d.]+\s*\)"),  # N(0,1), U(0,1)
    re.compile(r"_\(\s*[^()]*,[^()]*\)"),                  # индексы x_(1,2)
    re.compile(r"\{[^{}]*\}"),                             # множества {1,2,3}
    re.compile(r"\\\{[^{}]*\\\}"),                         # \{2,3\}
    re.compile(r"\(\s*-?\d+\s*(,\s*-?\d+\s*){1,3}\)"),     # кортежи (3,6)
    re.compile(r"\[\s*-?\d+\s*,\s*-?\d+\s*\]"),            # отрезки [0,1]
    re.compile(r"\b[A-ZΦF]\s*\(\s*\d+\s*,\s*\d+\s*\)"),    # F(2,4)
]


def без_комментариев(текст):
    """Строки-комментарии typst выкидываем: в них живут примеры «как не надо»."""
    return "\n".join("" if с.lstrip().startswith("//") else с for с in текст.split("\n"))


def проверить_файл(путь, корень):
    текст = без_комментариев(путь.read_text(encoding="utf-8"))
    отн = путь.relative_to(корень)
    находки = []
    for m in МАТРЕЖИМ.finditer(текст):
        фрагмент = m.group(0)
        очищенный = фрагмент
        for ш in РАЗДЕЛИТЕЛИ:
            очищенный = ш.sub(lambda s: " " * len(s.group(0)), очищенный)
        for d in ДЕСЯТИЧНАЯ.finditer(очищенный):
            н = текст.count("\n", 0, m.start() + d.start()) + 1
            находки.append(f'{отн}:{н}: сырая запятая «{d.group(0)}» — нужно dc("{d.group(0)}")')
    for н, строка in enumerate(текст.split("\n"), 1):
        if "{,}" in строка:
            находки.append(f"{отн}:{н}: {{,}} из LaTeX — нужно dc(...)")
        if "smallcaps(" in строка:
            находки.append(f"{отн}:{н}: smallcaps() не работает с кириллицей — нужно капитель(...)")
    return находки


def main():
    корень = pathlib.Path.cwd().resolve()
    папки = [pathlib.Path(a).resolve() for a in sys.argv[1:]] or [корень]
    файлы = []
    # Саму библиотеку и архив не проверяем: там эти строки — в примерах.
    пропуск = lambda ф: any(ч in ("lib", "архив", ".git") for ч in ф.relative_to(корень).parts[:-1])
    for п in папки:
        файлы += [ф for ф in п.rglob("*.typ") if not пропуск(ф)]
    всего = []
    for ф in sorted(set(файлы)):
        всего += проверить_файл(ф, корень)
    for x in всего:
        print(x)
    if всего:
        print(f"\nнайдено: {len(всего)}")
        return 1
    print(f"чисто ({len(файлы)} файлов)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
